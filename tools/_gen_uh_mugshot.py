"""Generate TEXTURES.uh_mugshot via Translation (Maestro-style). No baked PNGs.

SetFont/HudMessage works with Translation TEXTURES when HudMessage IDs are ordered
correctly (BACK highest ID). Templates must be playpal-indexed with the remap source
index (192/198/0/253).
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PAL = (ROOT / "ref/MM8BDM-v6b/PLAYPAL.pal").read_bytes()[:768]
OUT_TEX = ROOT / "src/TEXTURES.uh_mugshot"
FACES = ROOT / "src/patches/faces"
BAKE = ROOT / "src/patches/faces/uh_mugshot"

# (texture_prefix, template_relpath, source_palette_index)
LAYERS = (
    ("MGCYN", "megaman/MGCYN999.png", 192),
    ("MGBLU", "megaman/MGBLU999.png", 198),
    ("MGBLK", "megaman/MGBLK999.png", 0),
    ("QWCYN", "qwant/QWCYN999.png", 192),
    ("QWBLU", "qwant/QWBLU999.png", 198),
    ("NGPUR", "negaman/NGPUR999.png", 253),
)


def to_indexed_template(src: Path, color_index: int) -> None:
    """Opaque -> color_index (0 for black layer); transparent -> other index + tRNS."""
    rgba = Image.open(src).convert("RGBA")
    out = Image.new("P", rgba.size)
    out.putpalette(list(PAL))
    pin, pout = rgba.load(), out.load()
    if color_index == 0:
        # drawable=0, transparent=1 (Maestro MOBLK)
        for y in range(rgba.height):
            for x in range(rgba.width):
                *_, a = pin[x, y]
                pout[x, y] = 0 if a >= 128 else 1
        out.save(src, transparency=1)
    else:
        for y in range(rgba.height):
            for x in range(rgba.width):
                *_, a = pin[x, y]
                pout[x, y] = color_index if a >= 128 else 0
        out.save(src, transparency=0)
    print(f"template {src.name} -> {Counter(out.getdata()).most_common(3)}")


def emit_layer(lines: list[str], prefix: str, template: str, src_index: int) -> None:
    tmpl = Path(template).stem  # MGCYN999
    for n in range(256):
        lines.append(
            f'texture {prefix}{n:03d}, 32, 32{{XScale 4.0 YScale 4.0 '
            f'patch {tmpl}, 0, 0 {{Translation "{src_index}:{src_index}={n}:{n}"}}}}'
        )


def main() -> None:
    for prefix, rel, src_index in LAYERS:
        to_indexed_template(FACES / rel, src_index)

    lines = [
        "// UH per-class weapon-colored mugshots (generated by tools/_gen_uh_mugshot.py)",
        "// Translation from templates — same approach as v6b TEXTURES.MUGSHOT (Maestro).",
        "",
        "texture MEGABCK, 32, 32{XScale 4.0 YScale 4.0 patch MEGABACK, 0, 0}",
        "texture QWNTBCK, 32, 32{XScale 4.0 YScale 4.0 patch QWNTBACK, 0, 0}",
        "texture NEGABCK, 32, 32{XScale 4.0 YScale 4.0 patch NEGABACK, 0, 0}",
        "",
    ]
    for prefix, rel, src_index in LAYERS:
        emit_layer(lines, prefix, rel, src_index)
        lines.append("")

    OUT_TEX.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_TEX}")

    if BAKE.is_dir():
        n = 0
        for p in BAKE.glob("*.png"):
            p.unlink()
            n += 1
        print(f"removed {n} baked pngs from {BAKE}")


if __name__ == "__main__":
    main()
