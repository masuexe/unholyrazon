#!/usr/bin/env python3
"""Generate DecoyBot held-copy W1/W2/W3 actors from one W1 source per slot.

The source file is not a DECORATE include. W2/W3 normally differ only in
actor name, held base, tag, and 6Hxx sprite names. Slots 27 and 52 have
explicit W2/W3 overrides because their behavior differs from W1.
"""
from __future__ import annotations

import argparse
import difflib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/decoy_copy_moves_source.dec"
OUTPUT = ROOT / "src/actors/classes/survivors/decoy_copy_moves.dec"
SLOT_COUNT = 61
BASE_NAMES = tuple(f"DecoyCopyHeldBase_W{which}" for which in (1, 2, 3))
ACTOR_RE = re.compile(r"(?m)^actor\s+(DecoyCopy(?:HeldBase_W[123]|_\d{2}_W[123]))\b")
SPRITE_RE = re.compile(r"(?m)^(\s*)6H([A-Z0-9]{2})(?=\s)")


def read_actors(source: str) -> dict[str, str]:
    matches = list(ACTOR_RE.finditer(source))
    actors: dict[str, str] = {}
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(source)
        name = match.group(1)
        if name in actors:
            raise ValueError(f"duplicate source actor: {name}")
        actors[name] = source[match.start():end].strip()

    expected = set(BASE_NAMES)
    expected.update(f"DecoyCopy_{slot:02d}_W1" for slot in range(SLOT_COUNT))
    expected.update(f"DecoyCopy_{slot:02d}_W{which}" for slot in (27, 52) for which in (2, 3))
    if set(actors) != expected:
        missing = sorted(expected - set(actors))
        extra = sorted(set(actors) - expected)
        raise ValueError(f"source actor mismatch; missing={missing}, extra={extra}")
    return actors


def derive_slot(w1: str, slot: int, which: int) -> str:
    old_name = f"DecoyCopy_{slot:02d}_W1"
    new_name = f"DecoyCopy_{slot:02d}_W{which}"
    old_decl = f"actor {old_name} : DecoyCopyHeldBase_W1"
    old_tag = f'Tag "$TAG_{old_name}"'
    if w1.count(old_decl) != 1 or w1.count(old_tag) != 1:
        raise ValueError(f"slot {slot:02d}: unexpected W1 declaration or tag")
    result = w1.replace(old_decl, f"actor {new_name} : DecoyCopyHeldBase_W{which}", 1)
    result = result.replace(old_tag, f'Tag "$TAG_{new_name}"', 1)
    prefix = {2: "6I", 3: "6J"}[which]
    return SPRITE_RE.sub(lambda match: f"{match.group(1)}{prefix}{match.group(2)}", result)


def generate() -> str:
    actors = read_actors(SOURCE.read_text(encoding="utf-8"))
    header = (
        "// Generated by tools/gen_decoy_moves.py from tools/decoy_copy_moves_source.dec.\n"
        "// Edit the source, not this file. Use --check to verify generated output."
    )
    parts = [actors[name] for name in BASE_NAMES]
    for slot in range(SLOT_COUNT):
        w1 = actors[f"DecoyCopy_{slot:02d}_W1"]
        parts.append(w1)
        for which in (2, 3):
            name = f"DecoyCopy_{slot:02d}_W{which}"
            parts.append(actors.get(name) or derive_slot(w1, slot, which))
    return header + "\n\n" + "\n\n".join(parts) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    args = parser.parse_args()

    rendered = generate()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8")
        if current != rendered:
            diff = difflib.unified_diff(
                current.splitlines(), rendered.splitlines(),
                fromfile=str(OUTPUT), tofile="generated", lineterm=""
            )
            print("\n".join(list(diff)[:80]))
            raise SystemExit("generated DecoyBot moves are out of date")
        print("DecoyBot move output is up to date")
        return

    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({SLOT_COUNT * 3} copy actors)")


if __name__ == "__main__":
    main()
