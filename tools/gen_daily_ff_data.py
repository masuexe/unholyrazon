#!/usr/bin/env python3
"""Export baseline immunity and Qwant/Nega attack ownership for daily FF."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/acs_source/classes/shared/copy_weapons/daily_ff_data.acs'


def render():
    protection = (ROOT / 'src/actors/player/TeamProtection.dec').read_text()
    body = re.search(r'actor PowerProtectSurvivorBaseline\s*:\s*PowerProtection\s*\{(.*?)\n\}', protection, re.S).group(1)
    blocked = sorted(set(re.findall(r'damagefactor\s+"([^"]+)"\s*,\s*0\.0\b', body, re.I)), key=str.casefold)
    registration = (ROOT / 'src/acs_source/classes/shared/copy_weapons/copy_weapon_registration.acs').read_text()
    mapping = {}
    for kind, folder in [('QWANT', 'qwant_copyweps'), ('NEGA', 'negaman_copyweps')]:
        weapons = re.findall(r'DefineCopyWep\(UHCOPY_' + kind + r',\s*\w+,\s*"([^"]+)"', registration)
        files = list((ROOT / 'src/actors/classes/survivors' / folder).rglob('*.dec'))
        for weapon in weapons:
            matches = [p for p in files if re.search(r'\bactor\s+' + re.escape(weapon) + r'\s*:', p.read_text())]
            if len(matches) != 1:
                raise ValueError(f'{weapon}: expected one defining file, got {matches}')
            for actor in re.findall(r'^\s*actor\s+([^\s:{]+)', matches[0].read_text(), re.M | re.I):
                previous = mapping.get(actor)
                if previous and previous != weapon:
                    raise ValueError(f'Ambiguous attack {actor}: {previous}, {weapon}')
                mapping[actor] = weapon
    actors = sorted(mapping, key=str.casefold)
    puffs = set()
    for path in (ROOT / 'src/actors/classes/survivors').rglob('*.dec'):
        text = path.read_text()
        for call in re.finditer(r'\bA_(RailAttack|FireBullets)\s*\(', text):
            start = call.end()
            depth, quote, escaped, args = 1, '', False, []
            for i in range(start, len(text)):
                ch = text[i]
                if quote:
                    if escaped: escaped = False
                    elif ch == '\\': escaped = True
                    elif ch == quote: quote = ''
                elif ch in ('"', "'"): quote = ch
                elif ch == '(': depth += 1
                elif ch == ')':
                    depth -= 1
                    if depth == 0:
                        args.append(text[start:i].strip())
                        break
                elif ch == ',' and depth == 1:
                    args.append(text[start:i].strip())
                    start = i + 1
            index = 7 if call.group(1) == 'RailAttack' else 4
            if len(args) > index and re.fullmatch(r'"[^"\\]+"', args[index]):
                puffs.add(args[index][1:-1])
    result = '// Generated by tools/gen_daily_ff_data.py; do not edit.\n'
    for name, values in [('uh_ffblocked', blocked), ('uh_ffattack', actors),
                         ('uh_ffattackwep', [mapping[a] for a in actors]),
                         ('uh_ffpuff', sorted(puffs, key=str.casefold))]:
        result += f'#define {name.upper()}_COUNT {len(values)}\nstr {name}[{len(values)}] = {{\n'
        result += ',\n'.join(f'  "{value}"' for value in values) + '\n};\n\n'
    return result.rstrip() + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != data:
            raise SystemExit('daily_ff_data.acs is stale; run tools/gen_daily_ff_data.py')
        print('Daily FF baseline and attack ownership data match their sources.')
    else:
        OUTPUT.write_text(data)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')
